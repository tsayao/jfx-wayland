    /** Primitive kinds of C values. */
    private enum Kind {
        BYTE("byte", "JAVA_BYTE", 1),
        SHORT("short", "JAVA_SHORT", 2),
        INT("int", "JAVA_INT", 4),
        LONG("long", "JAVA_LONG", 8),
        FLOAT("float", "JAVA_FLOAT", 4),
        DOUBLE("double", "JAVA_DOUBLE", 8),
        ADDRESS("MemorySegment", "ADDRESS", 8);

        final String javaType;
        final String layout;
        final int size;

        Kind(String javaType, String layout, int size) {
            this.javaType = javaType;
            this.layout = layout;
            this.size = size;
        }
    }

    private record Member(String name, String type, int pointers, String arrayLen, String values,
                          boolean bitField) {}

    private record StructDef(String name, boolean union, List<Member> members) {}

    private record Param(String name, String type, int pointers) {}

    private record CommandDef(String name, String returnType, List<Param> params) {}

    private final Map<String, String> typeCategory = new HashMap<>();
    private final Map<String, String> typeAlias = new HashMap<>();
    private final Map<String, String> bitmaskBits = new HashMap<>();
    private final Map<String, Kind> bitmaskKind = new HashMap<>();
    private final Map<String, StructDef> structs = new HashMap<>();
    private final Map<String, CommandDef> commands = new HashMap<>();
    private final Map<String, String> commandAlias = new HashMap<>();
    private final Set<String> coreCommands = new HashSet<>();
    private final Map<String, Boolean> group64 = new HashMap<>();
    // Enum group name -> constant name -> value expression
    private final Map<String, Map<String, String>> groups = new LinkedHashMap<>();
    private final Map<String, String> enumAliases = new LinkedHashMap<>();
    private final Map<String, String> apiConstants = new LinkedHashMap<>();
    private final Map<String, String> apiConstantTypes = new HashMap<>();
    private final Map<String, String> extensionStrings = new TreeMap<>();

    @TaskAction
    public void generate() throws Exception {
        var factory = DocumentBuilderFactory.newInstance();
        Element root = factory.newDocumentBuilder().parse(registry).getDocumentElement();
        parseTypes(child(root, "types"));
        for (Element enums : children(root, "enums")) {
            parseEnums(enums);
        }
        parseCommands(child(root, "commands"));
        for (Element feature : children(root, "feature")) {
            if (supportsVulkan(feature.getAttribute("api"))) {
                parseRequires(feature, 0, CORE_VERSIONS.contains(feature.getAttribute("number")));
            }
        }
        for (Element ext : children(child(root, "extensions"), "extension")) {
            if (supportsVulkan(ext.getAttribute("supported"))) {
                parseRequires(ext, Integer.parseInt(ext.getAttribute("number")), false);
            }
        }

        Set<String> structClosure = structClosure();
        Set<String> usedGroups = usedGroups(structClosure);

        Path dir = outputDir.toPath().resolve(packageName.replace('.', '/'));
        Files.createDirectories(dir);
        for (String name : structClosure) {
            Files.writeString(dir.resolve(name + ".java"), generateStruct(structs.get(name)));
        }
        Files.writeString(dir.resolve("VK.java"), generateVK(usedGroups));
        getLogger().lifecycle("Generated " + structClosure.size() + " Vulkan structures and "
                + includeCommands.size() + " commands in " + dir);
    }

    private static boolean supportsVulkan(String api) {
        if (api == null || api.isEmpty()) {
            return true;
        }
        for (String a : api.split(",")) {
            if (a.equals("vulkan")) {
                return true;
            }
        }
        return false;
    }

    private void parseTypes(Element types) {
        for (Element type : children(types, "type")) {
            String name = typeName(type);
            if (!supportsVulkan(type.getAttribute("api")) || name == null || name.isEmpty()) {
                continue;
            }
            String category = type.getAttribute("category");
            typeCategory.put(name, category);
            if (type.hasAttribute("alias")) {
                typeAlias.put(name, type.getAttribute("alias"));
                continue;
            }
            switch (category) {
                case "bitmask" -> parseBitmask(type, name);
                case "struct", "union" -> structs.put(name, new StructDef(name, category.equals("union"), members(type)));
                default -> { }
            }
        }
    }

    /** The name of a type: its attribute, its name element, or that of its prototype for function pointers. */
    private static String typeName(Element type) {
        String name = type.hasAttribute("name") ? type.getAttribute("name") : textOf(child(type, "name"));
        if (name == null && child(type, "proto") != null) {
            name = textOf(child(child(type, "proto"), "name"));
        }
        return name;
    }

    /** The bits of a bitmask and whether it is 32 or 64 bits wide. */
    private void parseBitmask(Element type, String name) {
        String bits = type.hasAttribute("requires") ? type.getAttribute("requires") : type.getAttribute("bitvalues");
        if (!bits.isEmpty()) {
            bitmaskBits.put(name, bits);
        }
        String base = textOf(child(type, "type"));
        bitmaskKind.put(name, "VkFlags64".equals(base) ? Kind.LONG : Kind.INT);
    }

    /** The members of a structure or union that Vulkan has. */
    private List<Member> members(Element type) {
        List<Member> members = new ArrayList<>();
        for (Element m : children(type, "member")) {
            if (supportsVulkan(m.getAttribute("api"))) {
                members.add(parseMember(m));
            }
        }
        return members;
    }

    private Member parseMember(Element m) {
        String type = textOf(child(m, "type"));
        String name = textOf(child(m, "name"));
        int pointers = 0;
        String arrayLen = null;
        boolean afterName = false;
        boolean bitField = false;
        for (Node n = m.getFirstChild(); n != null; n = n.getNextSibling()) {
            if (n instanceof Element e) {
                if (e.getTagName().equals("name")) {
                    afterName = true;
                } else if (e.getTagName().equals("enum") && afterName) {
                    arrayLen = e.getTextContent();
                }
            } else if (n.getNodeType() == Node.TEXT_NODE) {
                String text = n.getTextContent();
                if (!afterName) {
                    pointers += count(text, '*');
                } else {
                    if (text.contains(":")) {
                        bitField = true;
                    }
                    int open = text.indexOf('[');
                    int close = text.indexOf(']');
                    if (open >= 0 && close > open + 1) {
                        arrayLen = text.substring(open + 1, close);
                    }
                }
            }
        }
        String values = m.hasAttribute("values") ? m.getAttribute("values") : null;
        return new Member(name, type, pointers, arrayLen, values, bitField);
    }

    private void parseEnums(Element enums) {
        String name = enums.getAttribute("name");
        String type = enums.getAttribute("type");
        // Registries before 1.3.2xx do not have type="constants"
        if (type.equals("constants") || name.equals("API Constants")) {
            for (Element e : children(enums, "enum")) {
                if (e.hasAttribute("alias")) {
                    enumAliases.put(e.getAttribute("name"), e.getAttribute("alias"));
                } else {
                    apiConstants.put(e.getAttribute("name"), e.getAttribute("value"));
                    apiConstantTypes.put(e.getAttribute("name"), e.getAttribute("type"));
                }
            }
            return;
        }
        if (!type.equals("enum") && !type.equals("bitmask")) {
            return;
        }
        group64.put(name, "64".equals(enums.getAttribute("bitwidth")));
        Map<String, String> values = groups.computeIfAbsent(name, k -> new LinkedHashMap<>());
        for (Element e : children(enums, "enum")) {
            if (!supportsVulkan(e.getAttribute("api"))) {
                continue;
            }
            addEnum(values, e, 0);
        }
    }

    private void addEnum(Map<String, String> values, Element e, int extNumber) {
        String name = e.getAttribute("name");
        if (e.hasAttribute("alias")) {
            enumAliases.put(name, e.getAttribute("alias"));
        } else if (e.hasAttribute("bitpos")) {
            values.put(name, "1L << " + e.getAttribute("bitpos"));
        } else if (e.hasAttribute("value")) {
            values.put(name, e.getAttribute("value"));
        } else if (e.hasAttribute("offset")) {
            int number = e.hasAttribute("extnumber") ? Integer.parseInt(e.getAttribute("extnumber")) : extNumber;
            long value = 1000000000L + (number - 1) * 1000L + Long.parseLong(e.getAttribute("offset"));
            if ("-".equals(e.getAttribute("dir"))) {
                value = -value;
            }
            values.put(name, Long.toString(value));
        }
    }

    private void parseCommands(Element commandsElement) {
        for (Element c : children(commandsElement, "command")) {
            if (!supportsVulkan(c.getAttribute("api"))) {
                continue;
            }
            if (c.hasAttribute("alias")) {
                commandAlias.put(c.getAttribute("name"), c.getAttribute("alias"));
                continue;
            }
            Element proto = child(c, "proto");
            String name = textOf(child(proto, "name"));
            String returnType = textOf(child(proto, "type"));
            List<Param> params = new ArrayList<>();
            for (Element p : children(c, "param")) {
                if (!supportsVulkan(p.getAttribute("api"))) {
                    continue;
                }
                Member m = parseMember(p);
                // Array parameters are pointers
                params.add(new Param(m.name(), m.type(), m.pointers() + (m.arrayLen() != null ? 1 : 0)));
            }
            commands.put(name, new CommandDef(name, returnType, params));
        }
    }

    private void parseRequires(Element owner, int extNumber, boolean core) {
        for (Element require : children(owner, "require")) {
            for (Element e : children(require, "enum")) {
                if (!supportsVulkan(e.getAttribute("api"))) {
                    continue;
                }
                String name = e.getAttribute("name");
                if (e.hasAttribute("extends")) {
                    addEnum(groups.computeIfAbsent(e.getAttribute("extends"), k -> new LinkedHashMap<>()),
                            e, extNumber);
                } else if (e.hasAttribute("value") && name.endsWith("_EXTENSION_NAME")) {
                    extensionStrings.put(name, e.getAttribute("value"));
                } else if (e.hasAttribute("alias") && !apiConstants.containsKey(name)) {
                    enumAliases.putIfAbsent(name, e.getAttribute("alias"));
                }
            }
            if (core) {
                for (Element c : children(require, "command")) {
                    coreCommands.add(c.getAttribute("name"));
                }
            }
        }
    }

    // ---------------------------------------------------------------------
    // Types

    private String resolveType(String type) {
        while (typeAlias.containsKey(type)) {
            type = typeAlias.get(type);
        }
        return type;
    }

    /** The kind of a C scalar type, or null for void and the other types. */
    private static Kind scalarKind(String type) {
        return switch (type) {
            case "char", "int8_t", "uint8_t" -> Kind.BYTE;
            case "int16_t", "uint16_t" -> Kind.SHORT;
            case "int", "int32_t", "uint32_t", "VkBool32", "VkFlags", "VkSampleMask" -> Kind.INT;
            case "int64_t", "uint64_t", "size_t", "VkDeviceSize", "VkDeviceAddress", "VkFlags64" -> Kind.LONG;
            case "float" -> Kind.FLOAT;
            case "double" -> Kind.DOUBLE;
            default -> null;
        };
    }

    private Kind kindOf(String type, int pointers) {
        if (pointers > 0) {
            return Kind.ADDRESS;
        }
        type = resolveType(type);
        Kind scalar = scalarKind(type);
        if (scalar != null || type.equals("void")) {
            return scalar;
        }
        String category = typeCategory.get(type);
        if (category == null) {
            throw new GradleException("Unknown type " + type);
        }
        return switch (category) {
            case "enum" -> Kind.INT;
            case "bitmask" -> bitmaskKind.getOrDefault(type, Kind.INT);
            // Handles are 64 bits on the 64-bit platforms JavaFX supports
            case "handle" -> Kind.LONG;
            case "funcpointer" -> Kind.ADDRESS;
            case "struct", "union" -> null;
            default -> throw new GradleException("Unsupported type " + type + " (" + category + ")");
        };
    }

    private boolean isStruct(String type) {
        String category = typeCategory.get(resolveType(type));
        return "struct".equals(category) || "union".equals(category);
    }

    private Set<String> structClosure() {
        Set<String> result = new LinkedHashSet<>();
        Deque<String> work = new ArrayDeque<>(includeStructs);
        while (!work.isEmpty()) {
            String name = resolveType(work.pop());
            if (!result.add(name)) {
                continue;
            }
            StructDef def = structs.get(name);
            if (def == null) {
                throw new GradleException("Unknown structure " + name);
            }
            for (Member m : def.members()) {
                if (m.pointers() == 0 && isStruct(m.type())) {
                    work.push(m.type());
                }
            }
        }
        return result;
    }

    private Set<String> usedGroups(Set<String> structClosure) {
        Set<String> used = new LinkedHashSet<>();
        used.add("VkResult");
        used.add("VkStructureType");
        for (String name : structClosure) {
            for (Member m : structs.get(name).members()) {
                addGroup(used, m.type());
            }
        }
        for (String name : includeCommands) {
            CommandDef def = commandDef(name);
            addGroup(used, def.returnType());
            for (Param p : def.params()) {
                addGroup(used, p.type());
            }
        }
        return used;
    }

    private void addGroup(Set<String> used, String type) {
        type = resolveType(type);
        String category = typeCategory.get(type);
        if ("enum".equals(category)) {
            used.add(type);
        } else if ("bitmask".equals(category) && bitmaskBits.containsKey(type)) {
            used.add(resolveType(bitmaskBits.get(type)));
        }
    }

    private CommandDef commandDef(String name) {
        String target = name;
        while (commandAlias.containsKey(target)) {
            target = commandAlias.get(target);
        }
        CommandDef def = commands.get(target);
        if (def == null) {
            throw new GradleException("Unknown command " + name);
        }
        return def;
    }

    // ---------------------------------------------------------------------
    // Layouts

    private record Field(Member member, long offset, long size, long align, Kind kind, long count) {}

    private record Layout(long size, long align, List<Field> fields) {}

    private final Map<String, Layout> layouts = new HashMap<>();

    private long arrayCount(String len) {
        if (len == null) {
            return 1;
        }
        if (len.chars().allMatch(Character::isDigit)) {
            return Long.parseLong(len);
        }
        String value = apiConstants.get(len);
        if (value == null) {
            throw new GradleException("Unknown array size " + len);
        }
        return Long.parseLong(value);
    }

    /** The C layout of a structure or union, computed once. */
    private Layout layoutOf(String structName) {
        String name = resolveType(structName);
        Layout cached = layouts.get(name);
        if (cached != null) {
            return cached;
        }
        StructDef def = structs.get(name);
        List<Field> fields = new ArrayList<>();
        long offset = 0;
        long maxAlign = 1;
        long maxSize = 0;
        for (Member m : def.members()) {
            Field field = memberField(name, m, def.union() ? 0 : offset);
            fields.add(field);
            maxSize = Math.max(maxSize, field.size());
            offset = field.offset() + field.size();
            maxAlign = Math.max(maxAlign, field.align());
        }
        long size = alignUp(def.union() ? maxSize : offset, maxAlign);
        Layout layout = new Layout(size, maxAlign, fields);
        layouts.put(name, layout);
        return layout;
    }

    /** A member placed at the first offset from a given one that its alignment allows. */
    private Field memberField(String structName, Member m, long offset) {
        if (m.bitField()) {
            throw new GradleException("Bit fields are not supported: " + structName + "." + m.name());
        }
        long count = arrayCount(m.arrayLen());
        Kind kind = kindOf(m.type(), m.pointers());
        long elemSize = kind != null ? kind.size : layoutOf(m.type()).size();
        long align = kind != null ? kind.size : layoutOf(m.type()).align();
        return new Field(m, alignUp(offset, align), elemSize * count, align, kind, count);
    }

    private static long alignUp(long value, long align) {
        return (value + align - 1) / align * align;
    }

    private String elementLayout(Field f) {
        if (f.kind() != null) {
            return "ValueLayout." + f.kind().layout;
        }
        return resolveType(f.member().type()) + ".LAYOUT";
    }

    // ---------------------------------------------------------------------
    // Structures

    private String generateStruct(StructDef def) {
        Layout layout = layoutOf(def.name());
        String sType = sTypeOf(layout);
        StringBuilder sb = new StringBuilder(HEADER);
        sb.append("package ").append(packageName).append(";\n\n");
        sb.append(STRUCT_IMPORTS);
        sb.append("/** The {@code ").append(def.name()).append("} ").append(def.union() ? "union" : "structure")
                .append(". */\n");
        sb.append("public final class ").append(def.name()).append(" {\n\n");
        sb.append("    public static final MemoryLayout LAYOUT = MemoryLayout.")
                .append(def.union() ? "unionLayout" : "structLayout").append("(\n");
        sb.append("        ").append(String.join(",\n        ", layoutElements(def, layout))).append(");\n\n");
        sb.append("    public static final long SIZEOF = ").append(layout.size()).append(";\n\n");
        for (Field f : layout.fields()) {
            sb.append("    private static final long OFFSET_").append(f.member().name()).append(" = ")
                    .append(f.offset()).append(";\n");
        }
        sb.append("\n    private ").append(def.name()).append("() {}\n\n");
        appendAllocators(sb, sType);
        for (Field f : layout.fields()) {
            generateAccessors(sb, f);
        }
        sb.append("}\n");
        return sb.toString();
    }

    private static final String STRUCT_IMPORTS = """
            import java.lang.foreign.MemoryLayout;
            import java.lang.foreign.MemorySegment;
            import java.lang.foreign.SegmentAllocator;
            import java.lang.foreign.ValueLayout;

            """;

    /** The value of the sType member of a structure, or null when it has none. */
    private static String sTypeOf(Layout layout) {
        String sType = null;
        for (Field f : layout.fields()) {
            if (f.member().name().equals("sType") && f.member().values() != null) {
                sType = f.member().values();
            }
        }
        return sType;
    }

    /** The members of the layout, with the padding of a structure between and after them. */
    private List<String> layoutElements(StructDef def, Layout layout) {
        List<String> elements = new ArrayList<>();
        long offset = 0;
        for (Field f : layout.fields()) {
            if (!def.union() && f.offset() > offset) {
                elements.add("MemoryLayout.paddingLayout(" + (f.offset() - offset) + ")");
            }
            String element = elementLayout(f);
            if (f.member().arrayLen() != null) {
                element = "MemoryLayout.sequenceLayout(" + f.count() + ", " + element + ")";
            }
            elements.add(element + ".withName(\"" + f.member().name() + "\")");
            offset = f.offset() + f.size();
        }
        if (!def.union() && layout.size() > offset) {
            elements.add("MemoryLayout.paddingLayout(" + (layout.size() - offset) + ")");
        }
        return elements;
    }

    /** allocate, allocateArray and at; the allocations set the sType of each instance. */
    private static void appendAllocators(StringBuilder sb, String sType) {
        sb.append("    /** Allocates a zeroed instance").append(sType != null ? " with its sType set" : "")
                .append(". */\n");
        sb.append("""
                    public static MemorySegment allocate(SegmentAllocator allocator) {
                        MemorySegment s = allocator.allocate(LAYOUT);
                        s.fill((byte) 0);
                """);
        if (sType != null) {
            sb.append("        s.set(ValueLayout.JAVA_INT, OFFSET_sType, VK.").append(sType).append(");\n");
        }
        sb.append("""
                        return s;
                    }

                    /** Allocates a zeroed array of instances. */
                    public static MemorySegment allocateArray(SegmentAllocator allocator, long count) {
                        MemorySegment s = allocator.allocate(LAYOUT, count);
                        s.fill((byte) 0);
                """);
        if (sType != null) {
            sb.append("        for (long i = 0; i < count; i++) {\n");
            sb.append("            s.set(ValueLayout.JAVA_INT, i * SIZEOF + OFFSET_sType, VK.").append(sType)
                    .append(");\n");
            sb.append("        }\n");
        }
        sb.append("""
                        return s;
                    }

                    /** The element of an array of instances. */
                    public static MemorySegment at(MemorySegment array, long index) {
                        return array.asSlice(index * SIZEOF, SIZEOF);
                    }
                """);
    }

    private void generateAccessors(StringBuilder sb, Field f) {
        String name = f.member().name();
        String off = "OFFSET_" + name;
        Kind kind = f.kind();
        boolean array = f.member().arrayLen() != null;
        sb.append("\n");
        if (kind == null || array) {
            sb.append("    public static MemorySegment ").append(name).append("(MemorySegment s) {\n");
            sb.append("        return s.asSlice(").append(off).append(", ").append(f.size()).append(");\n");
            sb.append("    }\n");
            if (kind != null) {
                String jt = kind.javaType;
                sb.append("\n    public static ").append(jt).append(" ").append(name)
                        .append("(MemorySegment s, int index) {\n");
                sb.append("        return s.get(ValueLayout.").append(kind.layout).append(", ").append(off)
                        .append(" + index * ").append(kind.size).append("L);\n    }\n");
                sb.append("\n    public static void ").append(name).append("(MemorySegment s, int index, ")
                        .append(jt).append(" value) {\n");
                sb.append("        s.set(ValueLayout.").append(kind.layout).append(", ").append(off)
                        .append(" + index * ").append(kind.size).append("L, value);\n    }\n");
            }
            return;
        }
        String jt = kind.javaType;
        sb.append("    public static ").append(jt).append(" ").append(name).append("(MemorySegment s) {\n");
        sb.append("        return s.get(ValueLayout.").append(kind.layout).append(", ").append(off).append(");\n");
        sb.append("    }\n\n");
        sb.append("    public static void ").append(name).append("(MemorySegment s, ").append(jt)
                .append(" value) {\n");
        sb.append("        s.set(ValueLayout.").append(kind.layout).append(", ").append(off)
                .append(", value);\n    }\n");
    }

